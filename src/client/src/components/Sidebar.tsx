function Sidebar() {
  const location = useLocation();
  const isSettingsPage = location.pathname.startsWith('/settings');

  return (
    <aside className="sidebar-container w-52 border-r flex flex-col">
      {/* Logo */}
      <div className="h-16 flex items-center px-4 border-b sidebar-border">
        <div className="flex items-center gap-2">
          <div className="w-8 h-8 logo-bg rounded-lg flex items-center justify-center">
            <svg className="w-5 h-5 text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M19 7l-.867 12.142A2 2 0 0116.138 21H7.862a2 2 0 01-1.995-1.858L5 7m5 4v6m4-6v6m1-10V4a1 1 0 00-1-1h-4a1 1 0 00-1 1v3M4 7h16" />
            </svg>
          </div>
          <span className="text-xl font-bold sidebar-title">Sweeparr</span>
        </div>
      </div>

      {/* Navigation */}
      <nav className="flex-1 px-3 py-4 space-y-1 overflow-y-auto sidebar-nav">
        {navigation.map((item) => (
          <div key={item.name}>
            <NavLink
              to={item.path}
              end={item.path === '/settings'}
              className={({ isActive }) => {
                const active = item.path === '/settings' ? isSettingsPage : isActive;
                return `sidebar-link ${active ? 'active' : ''}`;
              }}
            >
              <item.icon className="w-5 h-5" />
              {item.name}
            </NavLink>
            
            {/* Settings sub-navigation */}
            {item.name === 'Settings' && isSettingsPage && (
              <div className="ml-4 mt-1 space-y-1 border-l sidebar-border pl-2">
                {settingsSubNav.map((subItem) => (
                  <NavLink
                    key={subItem.name}
                    to={subItem.path}
                    end
                    className={({ isActive }) =>
                      `sidebar-sublink ${isActive ? 'active' : ''}`
                    }
                  >
                    <subItem.icon className="w-4 h-4" />
                    {subItem.name}
                  </NavLink>
                ))}
              </div>
            )}
          </div>
        ))}
      </nav>

      {/* Version */}
      <div className="px-4 py-4 border-t sidebar-border">
        <p className="text-xs sidebar-version">Version 0.1.0</p>
      </div>
    </aside>
  );
}

